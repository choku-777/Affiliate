    <h3 class="h6">アンバサダー利用規約</h3>
    <p>本規約は、大陸通商株式会社（以下「当社」といいます）が運営するアンバサダープログラム（以下「本プログラム」といいます）の利用に関する条件を定めるものです。本プログラムに登録される方（以下「アンバサダー」といいます）は、本規約に同意の上でご利用ください。</p>

    <p class="fw-bold mb-1">第1条（適用）</p>
    <p>本規約は、本プログラムの利用に関し、当社とアンバサダーとの間のいっさいの関係に適用されます。</p>

    <p class="fw-bold mb-1">第2条（登録）</p>
    <p>1. 登録希望者は、本規約に同意の上、当社所定の方法により登録を申請するものとします。<br>
    2. 当社が申請内容を審査し、これを承認した時点で登録が完了します。当社は、理由を開示することなく登録を承認しないことがあります。<br>
    3. 登録した情報に変更が生じた場合、アンバサダーは速やかに当社へ届け出るものとします。</p>

    <p class="fw-bold mb-1">第3条（報酬）</p>
    <p>1. 当社は、当社が定める条件を満たした成果（商品の購入等）に対し、当社所定の料率に基づく報酬を支払います。<br>
    2. 報酬は、成果が確定し、かつ当社が定める最低支払額以上に達した場合に、アンバサダーが登録した口座へ振り込みます。<br>
    3. 振込手数料その他の取り扱いは、当社の定めによるものとします。</p>

    <p class="fw-bold mb-1">第4条（成果の無効・取消）</p>
    <p>注文のキャンセル・返品・未入金、その他当社が不正または不適切と判断した場合、当社は対象となる成果および報酬を無効とし、または取り消すことができます。</p>

    <p class="fw-bold mb-1">第5条（禁止事項）</p>
    <p>アンバサダーは、本プログラムの利用にあたり、次の各号の行為を行ってはなりません。<br>
    (1) 虚偽の情報を登録する行為<br>
    (2) 不正なクリック、注文その他の方法により成果を不正に発生させる行為<br>
    (3) 自己または関係者による注文を成果として不正に計上する行為<br>
    (4) 当社または第三者の知的財産権、名誉、信用その他の権利・利益を侵害する行為<br>
    (5) 法令または公序良俗に違反する行為<br>
    (6) 当社の商品・ブランドの価値を損なう表示・宣伝を行う行為<br>
    (7) その他、当社が不適切と判断する行為</p>

    <p class="fw-bold mb-1">第6条（個人情報の取り扱い）</p>
    <p>当社は、登録された個人情報を、報酬の支払い、各種連絡、本プログラムの運営の目的の範囲で利用し、関係法令に従い適切に管理します。</p>

    <p class="fw-bold mb-1">第7条（登録の抹消・退会）</p>
    <p>1. アンバサダーは、当社所定の方法によりいつでも退会することができます。<br>
    2. アンバサダーが本規約に違反した場合、当社は事前の通知なく登録を抹消し、未払いの報酬を無効とすることができます。</p>

    <p class="fw-bold mb-1">第8条（免責）</p>
    <p>当社は、本プログラムに関連してアンバサダーに生じた損害について、当社の故意または重大な過失による場合を除き、責任を負わないものとします。</p>

    <p class="fw-bold mb-1">第9条（規約の変更）</p>
    <p>当社は、必要と判断した場合、本規約を変更できるものとし、変更後の規約は、当社が定める方法で告知した時点からその効力を生じます。</p>

    <p class="fw-bold mb-1">第10条（準拠法・管轄）</p>
    <p>本規約は日本法に準拠して解釈され、本プログラムに関して当社とアンバサダーとの間に生じた紛争については、当社の所在地を管轄する裁判所を第一審の専属的合意管轄裁判所とします。</p>

